import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { Config } from "@remotion/cli/config";
import { enableTailwind } from "@remotion/tailwind-v4";

// Remotion settings for this repo. The npm run video:* commands run from the repo root.
Config.setVideoImageFormat("jpeg");
// BT.709 in limited range (yuv420p), what phones and Instagram expect. With
// the "default" color space, JPEG frames come out as full-range yuvj420p.
Config.setPixelFormat("yuv420p");
Config.setColorSpace("bt709");
Config.setOverwriteOutput(true);
// The effects of @remotion/effects use WebGL.
Config.setChromiumOpenGlRenderer("angle");

/**
 * The registry of pieces the bundle sees. With REMOTION_PIECE (every npm run
 * video:* command sets it), only that piece: a module that imports its
 * video.tsx alone. Without it, every content/<piece>/video.tsx. Bundling all
 * 31 pieces took 38 s on 2026-11-03; one piece, a few seconds.
 */
function piecesModule(): string {
  const piece = process.env.REMOTION_PIECE;
  if (!piece || !/^[\w-]+$/.test(piece)) return resolve("packages/video/src/pieces.ts");
  const video = resolve("content", piece, "video.tsx").replace(/\\/g, "/");
  const file = resolve(".cache/remotion", `pieces-${piece}.ts`);
  mkdirSync(dirname(file), { recursive: true });
  const source = [
    "// Generated by packages/video/remotion.config.ts for one piece. Do not edit.",
    'import type { VideoDef } from "@motor/video";',
    `import video from ${JSON.stringify(video)};`,
    `export const PIECES: { id: string; video: VideoDef }[] = [{ id: ${JSON.stringify(piece)}, video }];`,
    "",
  ].join("\n");
  // Rewriting the same content would wake webpack's watcher in Studio for nothing.
  if (!existsSync(file) || readFileSync(file, "utf8") !== source) writeFileSync(file, source);
  return file;
}

Config.overrideWebpackConfig((config) => {
  const withTailwind = enableTailwind(config);
  return {
    ...withTailwind,
    resolve: {
      ...withTailwind.resolve,
      alias: {
        ...(withTailwind.resolve?.alias as Record<string, string> | undefined),
        "@motor/ui": resolve("packages/carousel/src/ui/index.tsx"),
        "@motor/video": resolve("packages/video/src/kit/index.ts"),
        "@motor/pieces": piecesModule(),
      },
    },
  };
});
