import type { ComponentType } from "react";
import { useStage } from "@motor/video";
import { BG, type BackProps } from "./palette.ts";
import { CierreBack } from "./scenes/cierre.tsx";
import { D1997Back } from "./scenes/d1997.tsx";
import { D2001Back } from "./scenes/d2001.tsx";
import { D2008Back } from "./scenes/d2008.tsx";
import { D2013Back } from "./scenes/d2013.tsx";
import { GanchoBack } from "./scenes/gancho.tsx";
import { PruebaBack } from "./scenes/prueba.tsx";
import { Ps5Back } from "./scenes/ps5.tsx";
import { ReboteBack } from "./scenes/rebote.tsx";
import { ReflejosBack } from "./scenes/reflejos.tsx";
import { TrazadoBack } from "./scenes/trazado.tsx";
import { TrucoBack } from "./scenes/truco.tsx";

/*
 * The world of "GTA 6 y la luz", a replica of a @rick.theengineer Reel: one
 * Miami-style coastal city that changes technique with the years. The world
 * draws each era full-bleed under the frame, as Rick does: the flat tile map
 * of 1997 and the isometric blocks of 2001 in code (map.tsx), and the
 * photoreal streets of GTA 6 as images generated by agy (img/). Each scene
 * file has its backdrop (drawn here, under the tab, the meter and the avatar)
 * and its Visual (the labels and the light on top). The pink hotel is the
 * thread: a roof in 1997, a lit facade today.
 */

const BACKS: Record<string, ComponentType<BackProps>> = {
  gancho: GanchoBack,
  d1997: D1997Back,
  d2001: D2001Back,
  d2008: D2008Back,
  d2013: D2013Back,
  truco: TrucoBack,
  trazado: TrazadoBack,
  rebote: ReboteBack,
  prueba: PruebaBack,
  reflejos: ReflejosBack,
  ps5: Ps5Back,
  cierre: CierreBack,
};

/** A word the way the voice timing writes it: lower case, no accents, no punctuation. */
const norm = (w: string) =>
  w
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9ñ]/g, "");

export function World() {
  const { sceneMs, sceneIndex, scenes } = useStage();
  const scene = scenes[sceneIndex];
  const Back = BACKS[scene.id];
  const cue = (word: string, nth = 1) => {
    const hit = scene.words.filter((w) => norm(w.text) === norm(word))[nth - 1];
    if (!hit) throw new Error(`"${word}" (time ${nth}) is not said in scene "${scene.id}"`);
    return hit.startMs / 1000;
  };
  return (
    <div className="absolute left-0 top-0 overflow-hidden" style={{ width: 540, height: 960, background: BG }}>
      {Back ? <Back t={sceneMs / 1000} cue={cue} /> : null}
    </div>
  );
}
